import re
import numpy as np
from collections import Counter
from scipy.sparse import csr_matrix
from sklearn.decomposition import TruncatedSVD

def clean_text(input_string, do_lower=True, strip_punctuation=False):
    if do_lower:
        input_string = input_string.lower()
    input_string = re.sub(r'<[^>]+>', ' ', input_string)
    if strip_punctuation:
        input_string = re.sub(r'[^\w\s]', ' ', input_string)
    input_string = re.sub(r'\s+', ' ', input_string).strip()
    return input_string

def tokenize(raw_text):
    return re.findall(r'\b\w+\b', raw_text.lower())

def split_train_val_test(corpus_data, targets, train_frac=0.7, val_frac=0.15, test_frac=0.15, seed_val=42):
    np.random.seed(seed_val)
    num_samples = len(corpus_data)
    shuffled_idx = np.random.permutation(num_samples)

    count_train = int(num_samples * train_frac)
    count_val = int(num_samples * val_frac)

    idx_train = shuffled_idx[:count_train]
    idx_val = shuffled_idx[count_train:count_train + count_val]
    idx_test = shuffled_idx[count_train + count_val:]

    train_docs = [corpus_data[i] for i in idx_train]
    train_lbls = [targets[i] for i in idx_train]

    val_docs = [corpus_data[i] for i in idx_val]
    val_lbls = [targets[i] for i in idx_val]

    test_docs = [corpus_data[i] for i in idx_test]
    test_lbls = [targets[i] for i in idx_test]

    return (train_docs, train_lbls), (val_docs, val_lbls), (test_docs, test_lbls)

def train_word_embeddings_ppmi_svd(docs_tokens, vec_size=100, ctx_window=3, max_terms=2000):
    term_freq = Counter()
    for doc in docs_tokens:
        term_freq.update(doc)

    valid_terms = [w for w, c in term_freq.most_common(max_terms) if c >= 2]
    term_to_id = {w: i for i, w in enumerate(valid_terms)}
    num_terms = len(valid_terms)

    if num_terms == 0:
        return {}, vec_size

    cooccur_freqs = Counter()
    for doc in docs_tokens:
        id_list = [term_to_id[w] for w in doc if w in term_to_id]
        doc_len = len(id_list)
        for i in range(doc_len):
            center = id_list[i]
            start_idx = max(0, i - ctx_window)
            end_idx = min(doc_len, i + ctx_window + 1)
            for j in range(start_idx, end_idx):
                if i != j:
                    cooccur_freqs[(center, id_list[j])] += 1

    if len(cooccur_freqs) == 0:
        return {w: np.zeros(vec_size, dtype=np.float32) for w in valid_terms}, vec_size

    row_idx = np.array([p[0] for p in cooccur_freqs.keys()], dtype=np.int32)
    col_idx = np.array([p[1] for p in cooccur_freqs.keys()], dtype=np.int32)
    val_data = np.array(list(cooccur_freqs.values()), dtype=np.float32)

    sparse_cooccur = csr_matrix((val_data, (row_idx, col_idx)), shape=(num_terms, num_terms), dtype=np.float32)
    sum_cooccur = float(val_data.sum())

    prob_word = np.array(sparse_cooccur.sum(axis=1)).flatten() / sum_cooccur
    prob_context = np.array(sparse_cooccur.sum(axis=0)).flatten() / sum_cooccur

    prob_joint = val_data / sum_cooccur
    exp_joint = prob_word[row_idx] * prob_context[col_idx]

    pmi_vals = np.log((prob_joint + 1e-12) / (exp_joint + 1e-12))
    ppmi_vals = np.maximum(pmi_vals, 0.0)

    sparse_ppmi = csr_matrix((ppmi_vals, (row_idx, col_idx)), shape=(num_terms, num_terms), dtype=np.float32)

    num_components = min(vec_size, num_terms - 1)
    trunc_svd = TruncatedSVD(n_components=num_components, random_state=42)
    dense_vectors = trunc_svd.fit_transform(sparse_ppmi)

    if num_components < vec_size:
        padding = np.zeros((num_terms, vec_size - num_components), dtype=np.float32)
        dense_vectors = np.hstack([dense_vectors, padding])

    emb_dict = {w: dense_vectors[i] for i, w in enumerate(valid_terms)}
    return emb_dict, vec_size

def compute_document_embedding(doc_tokens, emb_dict, vec_dim):
    found_vecs = [emb_dict[w] for w in doc_tokens if w in emb_dict]
    if len(found_vecs) == 0:
        return np.zeros(vec_dim, dtype=np.float32)
    return np.mean(found_vecs, axis=0).astype(np.float32)

def compute_corpus_embeddings(corpus_tokens, emb_dict, vec_dim):
    return np.array([
        compute_document_embedding(doc, emb_dict, vec_dim)
        for doc in corpus_tokens
    ], dtype=np.float32)

def compute_classification_metrics(actual_labels, predicted_labels):
    y_act = np.array(actual_labels)
    y_pred = np.array(predicted_labels)

    true_pos = int(np.sum((y_act == 1) & (y_pred == 1)))
    true_neg = int(np.sum((y_act == 0) & (y_pred == 0)))
    false_pos = int(np.sum((y_act == 0) & (y_pred == 1)))
    false_neg = int(np.sum((y_act == 1) & (y_pred == 0)))

    total_samples = true_pos + true_neg + false_pos + false_neg
    acc = (true_pos + true_neg) / total_samples if total_samples > 0 else 0.0
    prec = true_pos / (true_pos + false_pos) if (true_pos + false_pos) > 0 else 0.0
    rec = true_pos / (true_pos + false_neg) if (true_pos + false_neg) > 0 else 0.0
    f1_score = (2 * prec * rec) / (prec + rec) if (prec + rec) > 0 else 0.0

    return {
        "accuracy": float(acc),
        "precision": float(prec),
        "recall": float(rec),
        "f1": float(f1_score),
        "tp": true_pos,
        "tn": true_neg,
        "fp": false_pos,
        "fn": false_neg
    }

def compute_confusion_matrix(actual_labels, predicted_labels):
    y_act = np.array(actual_labels)
    y_pred = np.array(predicted_labels)

    true_pos = int(np.sum((y_act == 1) & (y_pred == 1)))
    true_neg = int(np.sum((y_act == 0) & (y_pred == 0)))
    false_pos = int(np.sum((y_act == 0) & (y_pred == 1)))
    false_neg = int(np.sum((y_act == 1) & (y_pred == 0)))

    return np.array([[true_pos, false_neg], [false_pos, true_neg]], dtype=int)
import numpy as np

class SimpleRNNCell:
    def __init__(self, input_size, hidden_size, random_seed=42):
        self.input_size = input_size
        self.hidden_size = hidden_size

        if random_seed is not None:
            np.random.seed(random_seed)

        bound_in = 1.0 / np.sqrt(input_size)
        self.W_xh = np.random.uniform(-bound_in, bound_in, (hidden_size, input_size)).astype(np.float32)

        bound_hid = 1.0 / np.sqrt(hidden_size)
        self.W_hh = np.random.uniform(-bound_hid, bound_hid, (hidden_size, hidden_size)).astype(np.float32)

        self.b_h = np.zeros((hidden_size, 1), dtype=np.float32)

    def forward(self, x_t, h_prev):
        has_single_dim = (x_t.ndim == 1)
        if has_single_dim:
            x_t = x_t.reshape(-1, 1)
        if h_prev.ndim == 1:
            h_prev = h_prev.reshape(-1, 1)
        bias_vec = self.b_h.reshape(-1, 1) if self.b_h.ndim == 1 else self.b_h
        activation = np.dot(self.W_xh, x_t) + np.dot(self.W_hh, h_prev) + bias_vec
        h_t = np.tanh(activation)
        if has_single_dim:
            return h_t.flatten()
        return h_t

    def init_hidden(self):
        return np.zeros((self.hidden_size, 1), dtype=np.float32)

class SimpleRNNSequence:
    def __init__(self, input_size, hidden_size, random_seed=42):
        self.cell = SimpleRNNCell(input_size, hidden_size, random_seed=random_seed)
        self.hidden_size = hidden_size

    def forward(self, sequence_x, h_0=None):
        if h_0 is None:
            curr_h = self.cell.init_hidden()
        else:
            curr_h = h_0

        history = []
        for item in sequence_x:
            curr_h = self.cell.forward(item, curr_h)
            history.append(curr_h)

        return history, curr_h

class SimpleRNNClassifier:
    def __init__(self, vocab_size, embedding_dim, hidden_size, num_classes=2, random_seed=42):
        self.hidden_size = hidden_size
        self.embedding_dim = embedding_dim

        if random_seed is not None:
            np.random.seed(random_seed)

        bound_emb = 1.0 / np.sqrt(embedding_dim)
        self.embeddings = np.random.uniform(-bound_emb, bound_emb, (vocab_size, embedding_dim)).astype(np.float32)

        self.rnn = SimpleRNNSequence(embedding_dim, hidden_size, random_seed=random_seed)

        bound_out = 1.0 / np.sqrt(hidden_size)
        self.W_hy = np.random.uniform(-bound_out, bound_out, (num_classes, hidden_size)).astype(np.float32)
        self.b_y = np.zeros((num_classes, 1), dtype=np.float32)

    def forward(self, token_ids):
        vec_list = [self.embeddings[idx] for idx in token_ids]
        _, final_state = self.rnn.forward(vec_list)
        raw_scores = np.dot(self.W_hy, final_state) + self.b_y
        scaled_exp = np.exp(raw_scores - np.max(raw_scores))
        probs = scaled_exp / np.sum(scaled_exp)
        return probs, final_state